import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parsePerformanceTime,normalizeDistance,findRecordCandidates} from '../dist/record-check.js';
const records=JSON.parse(readFileSync(new URL('../dist/data/records.json',import.meta.url),'utf8'));
assert.equal(records.length,22);
assert.equal(records.filter(r=>r.status==='unlisted').length,2);
assert.equal(new Set(records.map(r=>[r.category,r.gender,r.discipline].join('|'))).size,22);
assert.equal(parsePerformanceTime('2:23,40'),143.4);
assert.equal(parsePerformanceTime('2:23.40'),143.4);
assert.equal(parsePerformanceTime('1:09:17'),4157);
assert.equal(parsePerformanceTime('9:31,0'),571);
for(const t of ['DNF','DNS','–','',null,0,'0:00','1:70','1:20:99','1:02,3.4','3:-20']) assert.equal(parsePerformanceTime(t),null);
assert.equal(normalizeDistance('3 000 m hinder','track'),'3000mh');
assert.equal(normalizeDistance('3000mh','road'),null);
assert.equal(normalizeDistance('5 km','track'),'5000m');
assert.equal(normalizeDistance('5 km','road'),'5km');
assert.equal(normalizeDistance('Halvmaraton','road'),'half');
assert.equal(normalizeDistance('5 km','trail'),null);
const baseResult={athleteId:'test',name:'Testløper',gender:'K',distance:'10 km',time:'31:30',recordEligible:true};
const baseRace={id:'test',name:'Testløpet',date:'2026-10-30',type:'road',demo:false,results:[baseResult]};
const candidates=findRecordCandidates([baseRace],records);
assert.equal(candidates.length,1);
assert.equal(candidates[0].record.name,'Sofie Karoline Haugen');
assert.equal(candidates[0].improvementSeconds,1);
assert.equal(candidates[0].result,baseResult);
assert.equal(candidates[0].race,baseRace);
for(const patch of [{demo:true},{demo:undefined},{type:'trail'},{verified:false}]) assert.equal(findRecordCandidates([{...baseRace,...patch}],records).length,0);
for(const patch of [{recordEligible:false},{recordEligible:undefined},{status:'DNF'},{status:'DNS'},{verified:false},{time:'31:31'},{time:'31:32'}]) assert.equal(findRecordCandidates([{...baseRace,results:[{...baseResult,...patch}]}],records).length,0);
const track={...baseRace,type:'track',environment:'outdoor',results:[{...baseResult,gender:'M',distance:'800 m',time:'1:55,00'}]};
assert.equal(findRecordCandidates([track],records)[0].isFirstRecord,true);
assert.equal(findRecordCandidates([{...track,environment:'indoor'}],records).length,0);
assert.equal(findRecordCandidates([{...track,environment:undefined}],records).length,0);
const index=JSON.parse(readFileSync(new URL('../dist/data/index.json',import.meta.url),'utf8'));
const demos=index.races.map(path=>JSON.parse(readFileSync(new URL('../dist/'+path,import.meta.url),'utf8')));
assert.deepEqual(findRecordCandidates(demos,records),[]);
assert.equal(records.find(r=>r.category==='road'&&r.gender==='K'&&r.discipline==='10km').date,'2026-10-17');
assert.equal(records.find(r=>r.category==='track'&&r.gender==='M'&&r.discipline==='2000m').name,'Kristian Stokke Selnes');
console.log('PASS: 22 exact record slots; time parsing; category separation; demo/eligibility/status/outdoor gates; candidate calculation; no official mutation');
