#!/usr/bin/env python3
"""Extract exact supported-event thresholds from the official 2025 WA PDF.

Usage: python3 scripts/extract-wa-tables.py /path/to/wa-2025.pdf
Requires pypdf. The original PDF is not redistributed with this project.
The hash guard intentionally requires review before importing a new edition.
"""
import hashlib
import json
import logging
import pathlib
import re
import sys
from decimal import Decimal

from pypdf import PdfReader

SOURCE_URL = "https://worldathletics.org/download/download?filename=4f77dcb3-2945-4c58-ad8b-955a999b13e8.pdf&urlslug=World+Athletics+Scoring+Tables+of+Athletics"
SOURCE_SHA256 = "94ccf618257e38774a94744a9ffe3a8648e317f52cea97426596ec1ffbf5bb91"
# One-based first data page, number of columns excluding points, selected columns.
# PDF alternates the points column between the left and right edge.
GROUPS = [
    ("M", "track", 129, 6, {"800m": 2}),
    ("M", "track", 159, 8, {"1500m": 0, "2000m": 4}),
    ("M", "track", 189, 7, {"3000m": 0, "5000m": 4, "10000m": 6}),
    ("M", "road", 219, 6, {"5km": 1, "10km": 2}),
    ("M", "road", 249, 5, {"half": 0, "marathon": 3}),
    ("K", "track", 548, 6, {"800m": 2}),
    ("K", "track", 578, 8, {"1500m": 0, "2000m": 4}),
    ("K", "track", 608, 7, {"3000m": 0, "5000m": 4, "10000m": 6}),
    ("K", "road", 638, 6, {"5km": 1, "10km": 2}),
    ("K", "road", 668, 5, {"half": 0, "marathon": 3}),
]


def centiseconds(value):
    seconds = Decimal(0)
    for field in value.split(":"):
        seconds = seconds * 60 + Decimal(field)
    units = seconds * 100
    assert units == int(units), value
    return int(units)


def extract(pdf_path):
    digest = hashlib.sha256(pdf_path.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"Unexpected PDF SHA256 {digest}; review edition and pages first")
    logging.getLogger("pypdf").setLevel(logging.ERROR)
    reader = PdfReader(pdf_path)
    tables = {gender: {"road": {}, "track": {}} for gender in ("M", "K")}
    for gender, surface, first_page, column_count, columns in GROUPS:
        target = tables[gender][surface]
        for event in columns:
            target[event] = []
        seen_scores = []
        for page_index in range(first_page - 1, first_page + 27):
            page = reader.pages[page_index].extract_text(extraction_mode="layout")
            for line in page.splitlines():
                fields = line.split()
                if len(fields) != column_count + 1:
                    continue
                if re.fullmatch(r"\d{1,4}", fields[0]):
                    score, values = int(fields[0]), fields[1:]
                elif re.fullmatch(r"\d{1,4}", fields[-1]):
                    score, values = int(fields[-1]), fields[:-1]
                else:
                    continue
                if not all(value == "-" or re.fullmatch(r"\d+(?::\d+){1,2}(?:\.\d+)?", value) for value in values):
                    continue
                seen_scores.append(score)
                for event, column in columns.items():
                    value = values[column]
                    if value != "-":
                        target[event].append([centiseconds(value), score])
        assert seen_scores == list(range(1400, 0, -1)), (gender, surface, first_page)
        for event in columns:
            rows = target[event]
            assert rows and rows[-1][1] == 1, (gender, event)
            assert all(a[0] < b[0] and a[1] > b[1] for a, b in zip(rows, rows[1:])), (gender, event)
    return tables


def main():
    tables = extract(pathlib.Path(sys.argv[1]))
    target = pathlib.Path(__file__).resolve().parents[1] / "dist/wa-scoring-tables.js"
    header = """// Exact time thresholds from World Athletics Scoring Tables, 2025 revised edition.
// Generated by scripts/extract-wa-tables.py. Each pair is [centiseconds, points].
// Sparse road columns retain their actual published scores; no interpolation.
"""
    info = {"edition": "2025", "updatedAt": "2025-04-23", "checkedAt": "2026-11-11", "sourceUrl": SOURCE_URL,
            "sourceSha256": SOURCE_SHA256, "method": "world-athletics-2025", "minScore": 1, "maxScore": 1400}
    lines = [header, "export const WA_SCORING_INFO=Object.freeze(" + json.dumps(info, ensure_ascii=False, separators=(",", ":")) + ");\n",
             "export const WA_SCORING_TABLES=Object.freeze({\n"]
    for gender, surfaces in tables.items():
        lines.append(f"  {gender}:Object.freeze({{\n")
        for surface, events in surfaces.items():
            lines.append(f"    {surface}:Object.freeze({{\n")
            for event, rows in events.items():
                lines.append(f"      {json.dumps(event)}:Object.freeze(" + json.dumps(rows, separators=(",", ":")) + ".map(Object.freeze)),\n")
            lines.append("    }),\n")
        lines.append("  }),\n")
    lines.append("});\n")
    target.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote {target} ({target.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
